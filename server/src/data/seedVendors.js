// Helper to generate 11 documents with specific verification counts
function generateDocuments(verifiedCount = 11, rejectedCount = 0, uploadedOnlyCount = 0) {
  return REQUIRED_DOCUMENT_TYPES.map((docType, index) => {
    let status = DOCUMENT_STATUS.VERIFIED;
    let remarks = 'Verified against government registry and regulatory portal.';
    let verifiedAt = '2026-09-15T11:30:00Z';
    let verifiedBy = 'Pooja Verma (Procurement)';

    if (index < verifiedCount) {
      status = DOCUMENT_STATUS.VERIFIED;
    } else if (index < verifiedCount + rejectedCount) {
      status = DOCUMENT_STATUS.REJECTED;
      remarks = 'Document expired / illegible seal. Resubmission required.';
      verifiedAt = '2026-09-18T14:20:00Z';
    } else if (index < verifiedCount + rejectedCount + uploadedOnlyCount) {
      status = DOCUMENT_STATUS.UPLOADED;
      remarks = 'Pending procurement officer review.';
      verifiedAt = null;
      verifiedBy = null;
    } else {
      status = DOCUMENT_STATUS.PENDING;
      remarks = 'Awaiting vendor upload.';
      verifiedAt = null;
      verifiedBy = null;
    }

    return {
      id: `doc_${docType.id}`,
      documentTypeId: docType.id,
      name: docType.name,
      category: docType.category,
      fileName: status !== DOCUMENT_STATUS.PENDING ? `${docType.id}_signed_copy.pdf` : null,
      fileSize: status !== DOCUMENT_STATUS.PENDING ? '1.8 MB' : null,
      uploadedAt: status !== DOCUMENT_STATUS.PENDING ? '2026-09-12T10:00:00Z' : null,
      status: status,
      remarks: remarks,
      verifiedAt: verifiedAt,
      verifiedBy: verifiedBy,
    };
  });
}

function calculateVerificationStats(docs) {
  const verified = docs.filter(d => d.status === DOCUMENT_STATUS.VERIFIED).length;
  const total = docs.length;
  return {
    verifiedCount: verified,
    totalCount: total,
    progressPercent: Math.round((verified / total) * 100),
    summary: `${verified} / ${total} documents verified`,
  };
}

